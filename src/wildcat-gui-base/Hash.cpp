#define PRIME_MULT 1717

uint32_t Hash::gen32(const std::string s)
{
    if( s.empty())
        return 0;

    size_t len = s.length();

    uint32_t hash = (uint32_t)len;

    for (size_t i = 0; i < len; ++i)
    {
        hash ^= sTable[(s[i] + i) & 255];
        hash = hash * PRIME_MULT;
    }

    return hash;
}


